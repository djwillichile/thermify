# Station validation engine. Inputs are synthetic hourly series built with
# known diurnal models, so that the expected agreement is known exactly.

hourly_station_fixture <- function(start = "2019-01-01", end = "2022-12-31",
                                   const_tmin = FALSE, seed = 1) {
  set.seed(seed)
  dates <- seq(as.Date(start), as.Date(end), by = "day")
  doy <- as.integer(format(dates, "%j"))
  tmin <- if (const_tmin) rep(3, length(dates)) else
    6 + 4 * cos(2 * pi * (doy - 15) / 365) + stats::rnorm(length(dates), 0, 2)
  tmax <- tmin + 11 + stats::runif(length(dates), 0, 4)
  h <- hourly_temperatures(tmin, tmax, "sine")
  time <- as.POSIXct(paste(rep(format(dates), each = 24),
                           sprintf("%02d:00", rep(0:23, length(dates)))),
                     tz = "Etc/GMT+4")
  list(time = time, temperature = h, dates = dates)
}

test_that("gaps are filled only when short, and days are flagged", {
  f <- hourly_station_fixture("2021-01-01", "2021-01-10")
  temp <- f$temperature
  temp[30:31] <- NA          # 2 h gap: filled
  temp[100:104] <- NA        # 5 h gap: not filled
  st <- prepare_station_hourly(f$time, temp, max_gap = 2)
  expect_s3_class(st, "station_hourly")
  expect_equal(dim(st$hourly), c(10, 24))
  expect_equal(st$quality$filled, 2)
  expect_equal(st$quality$missing, 5)
  expect_equal(which(!st$valid), 5)
  # Hourly index 30 is day 2, hour 5 (column 6).
  expect_equal(st$hourly[2, 6:7], stats::approx(c(29, 32),
               f$temperature[c(29, 32)], xout = 30:31)$y)
  expect_output(print(st), "1 missing|5 missing")
})

test_that("implausible values, duplicates and sub-hourly records", {
  t0 <- as.POSIXct("2021-05-01 00:00", tz = "UTC")
  time <- c(t0 + 3600 * (0:47), t0 + 1800)       # one extra half-hour value
  temp <- c(rep(5, 48), 7)
  temp[10] <- 99                                  # out of range -> NA -> filled
  st <- prepare_station_hourly(time, temp)
  expect_equal(st$hourly[1, 1], 6)                # mean of 5 and 7
  expect_equal(st$hourly[1, 10], 5)
  expect_true(all(st$valid))
  expect_error(prepare_station_hourly(as.character(time), temp), "POSIXct")
})

test_that("metrics follow their definitions", {
  m <- validation_metrics(c(12, 14, 9, NA), c(10, 15, 10, 3))
  expect_equal(m$n, 3)
  expect_equal(m$bias, (2 - 1 - 1) / 3)
  expect_equal(m$mae, 4 / 3)
  expect_equal(m$rmse, sqrt(6 / 3))
  expect_equal(m$rel_bias, 100 * m$bias / mean(c(10, 15, 10)))
  expect_equal(m$r, stats::cor(c(12, 14, 9), c(10, 15, 10)))
  expect_true(is.na(validation_metrics(c(1, -1), c(1, -1))$rel_bias))
  expect_true(is.na(validation_metrics(1, 2)$r))
})

test_that("a station generated by the sine model is reproduced exactly", {
  # With a constant minimum, daily extremes taken from the hourly record
  # equal the generating extremes, so the sine reconstruction is exact.
  f <- hourly_station_fixture("2019-01-01", "2021-12-31", const_tmin = TRUE)
  st <- prepare_station_hourly(f$time, f$temperature)
  v <- validate_station(st, latitude = -35.97, hourly_methods = "sine",
                        indices = c("ch", "cu", "cp"))
  d <- v$seasons[v$seasons$level == "daily" &
                   v$seasons$method == "hourly_sine", ]
  expect_gt(nrow(d), 0)
  expect_equal(d$estimate, d$observed, tolerance = 1e-10)
})

test_that("seasons, levels and exclusions are reported", {
  f <- hourly_station_fixture()
  temp <- f$temperature
  temp[9000:9010] <- NA      # 11 h gap in January 2020
  st <- prepare_station_hourly(f$time, temp)
  v <- validate_station(st, latitude = -35.97,
                        gridded = list(tmin = rep(5, 12), tmax = rep(17, 12)))
  expect_s3_class(v, "thermify_validation")
  expect_setequal(unique(v$seasons$level), c("daily", "monthly", "gridded"))
  # Chill seasons 2019-2022 complete; heat seasons: 2018 and 2022 incomplete,
  # 2019 has an invalid day.
  expect_setequal(unique(v$seasons$season[v$seasons$index == "cp"]),
                  2019:2022)
  expect_setequal(unique(v$seasons$season[v$seasons$index == "gdd"]),
                  c(2020, 2021))
  ex <- v$excluded[v$excluded$index == "gdd", ]
  expect_setequal(ex$season, c(2018, 2019, 2022))
  expect_match(ex$reason[ex$season == 2019], "invalid")
  # One climatological estimate per method, compared with every season.
  mon <- v$seasons[v$seasons$level == "monthly" & v$seasons$index == "cp" &
                     v$seasons$method == "hourly_linvill", ]
  expect_length(unique(mon$estimate), 1)
  expect_equal(nrow(mon), 4)
  # Observed values are shared across levels.
  obs <- unique(v$seasons[v$seasons$index == "cp",
                          c("season", "observed")])
  expect_equal(nrow(obs), 4)
  expect_true(all(c("bias", "mae", "rmse", "rel_bias", "r") %in%
                    names(v$metrics)))
  expect_output(print(v), "season\\(s\\) evaluated")
})

test_that("observed indices equal the direct hourly computations", {
  f <- hourly_station_fixture("2020-01-01", "2020-12-31")
  st <- prepare_station_hourly(f$time, f$temperature)
  v <- validate_station(st, latitude = -35.97, indices = c("cp", "ch"),
                        hourly_methods = "sine")
  days <- which(st$dates >= as.Date("2020-05-01") &
                  st$dates <= as.Date("2020-08-31"))
  h <- as.vector(t(st$hourly[days, ]))
  cp <- v$seasons$observed[v$seasons$index == "cp"][1]
  expect_equal(cp, as.vector(chill_portions(h, output = "total")))
  ch <- v$seasons$observed[v$seasons$index == "ch"][1]
  expect_equal(ch, sum(h >= 0 & h <= 7.2))
})

test_that("invalid arguments are rejected", {
  f <- hourly_station_fixture("2020-01-01", "2020-12-31")
  st <- prepare_station_hourly(f$time, f$temperature)
  expect_error(validate_station(list(), -35), "prepare_station_hourly")
  expect_error(validate_station(st, -35, base = c(5, 10)), "one `base`")
  expect_error(validate_station(st, -35, gridded = list(tmin = 1:3)),
               "12 monthly")
})
